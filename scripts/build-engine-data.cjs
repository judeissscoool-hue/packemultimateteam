const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const match = html.match(/<script>\s*\/\/<LOGIC>([\s\S]*?)\/\/<\/LOGIC>\s*<\/script>/);
if (!match) throw new Error("Could not find the canonical //<LOGIC> block in index.html");

const context = vm.createContext({ console, Math, Object, Array, Set, Map, JSON });
vm.runInContext(`${match[1]}\n;globalThis.__atuExport={DB,DUOS,SPOTLIGHT};`, context, {
  filename: "index.html#logic"
});

const cards = context.__atuExport.DB.filter(Boolean).map(card => ({
  id: card.id,
  n: card.name,
  p: card.pos,
  ps: Array.from(card.positions),
  o: card.ovr,
  t: card.team,
  r: card.tier,
  w: context.__atuExport.SPOTLIGHT[card.name] ?? 1,
  g: Array.from(card.tags)
}));
const duos = context.__atuExport.DUOS.map(group => ({
  l: group.l,
  m: Array.from(group.m)
}));

const banner = `// Generated by scripts/build-engine-data.cjs from the canonical index.html logic.\n`
  + `// Do not edit by hand; rerun the generator after changing cards or chemistry groups.\n`;
const output = `${banner}export const CARDS=${JSON.stringify(cards)};\nexport const DUOS=${JSON.stringify(duos)};\n`;
const destination = path.join(root, "supabase", "functions", "_shared", "atu-data-v1.js");
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, output);
console.log(`generated ${cards.length} cards and ${duos.length} chemistry groups`);
