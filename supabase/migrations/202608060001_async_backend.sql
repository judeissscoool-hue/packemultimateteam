create or replace function public.set_username(p_username text)
returns public.profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  clean_username text := trim(p_username);
  updated_profile public.profiles;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if clean_username !~ '^[A-Za-z0-9_]{3,20}$' then
    raise exception 'Username must be 3-20 characters using letters, numbers or underscores';
  end if;

  update public.profiles
  set username = clean_username
  where id = auth.uid()
  returning * into updated_profile;

  if updated_profile.id is null then
    raise exception 'Profile not found';
  end if;

  return updated_profile;
exception
  when unique_violation then
    raise exception 'Username is already taken';
end;
$$;

create or replace function public.create_async_challenge(p_rules_version text)
returns table (challenge_id uuid, challenge_code text, draft_seed text, expires_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  new_challenge public.async_challenges;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if nullif(trim(p_rules_version), '') is null then
    raise exception 'Rules version is required';
  end if;

  insert into public.async_challenges (
    code,
    created_by,
    rules_version,
    draft_seed
  )
  values (
    upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 12)),
    auth.uid(),
    trim(p_rules_version),
    encode(gen_random_bytes(16), 'hex')
  )
  returning * into new_challenge;

  return query
  select new_challenge.id, new_challenge.code, new_challenge.draft_seed, new_challenge.expires_at;
end;
$$;

create or replace function public.get_async_challenge(p_code text)
returns table (
  challenge_id uuid,
  challenge_code text,
  status text,
  creator_username text,
  rules_version text,
  draft_seed text,
  has_opponent boolean,
  expires_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.id,
    c.code,
    case when c.expires_at <= now() and c.status in ('open', 'accepted')
      then 'expired' else c.status end,
    coalesce(p.username, p.display_name, 'Player'),
    c.rules_version,
    c.draft_seed,
    c.opponent_id is not null,
    c.expires_at
  from public.async_challenges c
  join public.profiles p on p.id = c.created_by
  where c.code = upper(trim(p_code))
    and c.status <> 'cancelled'
  limit 1;
$$;

create or replace function public.accept_async_challenge(p_code text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  target public.async_challenges;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  select *
  into target
  from public.async_challenges
  where code = upper(trim(p_code))
  for update;

  if target.id is null then
    raise exception 'Challenge not found';
  end if;
  if target.expires_at <= now() then
    update public.async_challenges set status = 'expired' where id = target.id;
    raise exception 'Challenge has expired';
  end if;
  if target.created_by = auth.uid() then
    raise exception 'You cannot accept your own challenge';
  end if;
  if target.status <> 'open' or target.opponent_id is not null then
    raise exception 'Challenge is no longer available';
  end if;

  update public.async_challenges
  set opponent_id = auth.uid(), status = 'accepted'
  where id = target.id;

  return target.id;
end;
$$;

create or replace function public.get_leaderboard(
  p_mode text,
  p_period text default 'all_time',
  p_limit integer default 50
)
returns table (
  rank bigint,
  user_id uuid,
  username text,
  avatar_url text,
  games bigint,
  points numeric,
  wins bigint,
  losses bigint
)
language sql
stable
security definer
set search_path = public
as $$
  with filtered as (
    select l.*
    from public.leaderboard_entries l
    where l.mode = p_mode
      and p_mode in ('draft', 'pack', 'one_v_one')
      and l.created_at >= case p_period
        when 'daily' then date_trunc('day', now())
        when 'weekly' then date_trunc('week', now())
        else '-infinity'::timestamptz
      end
  ),
  totals as (
    select
      f.user_id,
      count(*) as games,
      sum(f.points) as points,
      sum(f.wins)::bigint as wins,
      sum(f.losses)::bigint as losses
    from filtered f
    group by f.user_id
  ),
  ranked as (
    select
      row_number() over (order by t.points desc, t.wins desc, t.games asc, t.user_id) as rank,
      t.*
    from totals t
  )
  select
    r.rank,
    r.user_id,
    coalesce(p.username, p.display_name, 'Player') as username,
    p.avatar_url,
    r.games,
    r.points,
    r.wins,
    r.losses
  from ranked r
  join public.profiles p on p.id = r.user_id
  order by r.rank
  limit greatest(1, least(coalesce(p_limit, 50), 100));
$$;

