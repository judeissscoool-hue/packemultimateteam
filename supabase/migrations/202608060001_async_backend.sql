create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text,
  display_name text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (
    username is null or username ~ '^[A-Za-z0-9_]{3,20}$'
  ),
  constraint profiles_display_name_length check (
    display_name is null or char_length(display_name) between 1 and 40
  )
);

create unique index if not exists profiles_username_lower_unique
  on public.profiles (lower(username))
  where username is not null;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, avatar_url)
  values (
    new.id,
    nullif(coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name'), ''),
    nullif(coalesce(new.raw_user_meta_data ->> 'avatar_url', new.raw_user_meta_data ->> 'picture'), '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create table if not exists public.cloud_saves (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  schema_version integer not null default 1 check (schema_version > 0),
  payload jsonb not null default '{}'::jsonb,
  client_updated_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint cloud_saves_payload_object check (jsonb_typeof(payload) = 'object')
);

drop trigger if exists cloud_saves_set_updated_at on public.cloud_saves;
create trigger cloud_saves_set_updated_at
before update on public.cloud_saves
for each row execute function public.set_updated_at();

create table if not exists public.async_challenges (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  created_by uuid not null references public.profiles(id) on delete cascade,
  opponent_id uuid references public.profiles(id) on delete set null,
  winner_id uuid references public.profiles(id) on delete set null,
  status text not null default 'open'
    check (status in ('open', 'accepted', 'completed', 'expired', 'cancelled')),
  rules_version text not null,
  draft_seed text not null,
  expires_at timestamptz not null default (now() + interval '7 days'),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint async_challenges_distinct_players check (
    opponent_id is null or opponent_id <> created_by
  ),
  constraint async_challenges_winner_is_player check (
    winner_id is null or winner_id = created_by or winner_id = opponent_id
  )
);

create index if not exists async_challenges_created_by_idx
  on public.async_challenges (created_by, created_at desc);
create index if not exists async_challenges_opponent_idx
  on public.async_challenges (opponent_id, created_at desc)
  where opponent_id is not null;
create index if not exists async_challenges_status_expiry_idx
